using System.Globalization;

namespace NexusSSH.Core.Localization;

/// <summary>Sprache der Oberfläche.</summary>
public enum AppLanguage
{
    /// <summary>Nach der Windows-Anzeigesprache.</summary>
    Auto,
    German,
    English,
    French,
    Spanish,
}

/// <summary>
/// Kleine, AOT-sichere Lokalisierung ohne <c>.resw</c>/PRI: je Sprache ein Wörterbuch, zur Laufzeit über den
/// Schlüssel abgefragt. Deutsch und Englisch stehen hier, jede weitere Sprache in einer eigenen Datei daneben
/// (<c>L.Fr.cs</c>, <c>L.Es.cs</c>). Die Sprache wird beim Start aus den Einstellungen gesetzt (<see cref="Init"/>);
/// ein Wechsel greift nach einem Neustart. XAML nutzt die Markup-Extension <c>{loc:Loc Key=…}</c>, Code ruft
/// <see cref="Get(string)"/> – immer mit dem Schlüssel als Literal, damit <c>LocalizationTests</c> ihn findet.
/// <para>
/// Eine weitere Sprache braucht: einen Wert in <see cref="AppLanguage"/> (hinten anhängen – die Auswahl in den
/// Einstellungen zählt mit), ihr Wörterbuch, je einen Eintrag in <see cref="Init"/>, <c>Texts</c> und
/// <see cref="Culture"/>, die Namen der Tasten in <c>KeyChord</c> und ihren Namen in der Auswahl der Einstellungen.
/// Die Tests verlangen in jeder Sprache dieselben Schlüssel und Platzhalter.
/// </para>
/// </summary>
public static partial class L
{
    /// <summary>Die Sprache, in der die Oberfläche gerade spricht – nie <see cref="AppLanguage.Auto"/>.</summary>
    public static AppLanguage Language { get; private set; } = AppLanguage.English;

    /// <summary>Ist die Oberfläche aktuell englisch?</summary>
    public static bool English => Language == AppLanguage.English;

    /// <summary>Kultur für Zahlen und Uhrzeiten in der gewählten Sprache (Dezimaltrennzeichen).</summary>
    public static CultureInfo Culture => Language switch
    {
        AppLanguage.German => GermanCulture,
        AppLanguage.French => FrenchCulture,
        AppLanguage.Spanish => SpanishCulture,
        _ => EnglishCulture,
    };

    /// <summary>Setzt die Sprache. <c>Auto</c> = die Windows-Anzeigesprache, wenn es sie hier gibt, sonst Englisch.</summary>
    public static void Init(AppLanguage language)
    {
        Language = language switch
        {
            AppLanguage.English or AppLanguage.German or AppLanguage.French or AppLanguage.Spanish => language,
            _ => FromCulture(CultureInfo.CurrentUICulture.TwoLetterISOLanguageName),
        };
    }

    /// <summary>Die Sprache zu einem Kürzel wie <c>de</c> oder <c>fr</c>; alles Unbekannte ist Englisch.</summary>
    public static AppLanguage FromCulture(string twoLetters) => twoLetters.ToLowerInvariant() switch
    {
        "de" => AppLanguage.German,
        "fr" => AppLanguage.French,
        "es" => AppLanguage.Spanish,
        _ => AppLanguage.English,
    };

    /// <summary>Übersetzung zum Schlüssel; fehlt sie, kommt der Schlüssel selbst zurück (fällt im Test auf).</summary>
    public static string Get(string key) => Texts(Language).TryGetValue(key, out var value) ? value : key;

    /// <summary>Das Wörterbuch einer Sprache.</summary>
    internal static IReadOnlyDictionary<string, string> Texts(AppLanguage language) => language switch
    {
        AppLanguage.German => De,
        AppLanguage.French => Fr,
        AppLanguage.Spanish => Es,
        _ => En,
    };

    /// <summary>Alle Sprachen, die es gibt – ohne <see cref="AppLanguage.Auto"/>.</summary>
    internal static IReadOnlyList<AppLanguage> Languages { get; } = [AppLanguage.German, AppLanguage.English, AppLanguage.French, AppLanguage.Spanish];

    /// <summary>Wie <see cref="Get(string)"/>, aber mit <c>{0}</c>/<c>{1}</c>-Platzhaltern (invariante Formatierung).</summary>
    public static string Get(string key, params object?[] args) => string.Format(CultureInfo.InvariantCulture, Get(key), args);

    internal static IReadOnlyDictionary<string, string> German => De;

    internal static IReadOnlyDictionary<string, string> EnglishTexts => En;

